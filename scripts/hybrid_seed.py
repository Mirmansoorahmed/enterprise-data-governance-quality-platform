"""Generate scripts/hybrid_seed_sql.sql for the live Azure SQL smoke test.

Writes a CREATE TABLE + INSERT script for the Finance source table, built ONLY
from the synthetic finance extract (data/raw/finance/finance_postings.csv). No
HR data, no real data. Paste the generated file into the Azure portal Query
editor during a create-test-delete session (see docs/HYBRID.md).

Usage:
    python3 scripts/hybrid_seed.py        # writes scripts/hybrid_seed_sql.sql

Standard-library only.
"""

from __future__ import annotations

import csv
import os

HERE = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.dirname(HERE)
FINANCE_CSV = os.path.join(REPO_ROOT, "data", "raw", "finance", "finance_postings.csv")
OUT = os.path.join(HERE, "hybrid_seed_sql.sql")

TABLE = "finance_postings"

# Column -> SQL type. Matches the synthetic finance extract shape. amount is
# numeric; the rest are short strings.
COLUMNS = [
    ("posting_id", "NVARCHAR(32)"),
    ("company", "NVARCHAR(16)"),
    ("cost_centre_id", "NVARCHAR(32)"),
    ("amount", "DECIMAL(18,2)"),
]
NUMERIC = {"amount"}


def _sql_literal(column: str, value: str) -> str:
    if column in NUMERIC:
        # Validate it is a number; never interpolate arbitrary text as numeric.
        return f"{float(value):.2f}"
    return "N'" + value.replace("'", "''") + "'"


def build_sql() -> str:
    with open(FINANCE_CSV, "r", encoding="utf-8", newline="") as fh:
        rows = list(csv.DictReader(fh))

    lines: list[str] = []
    lines.append("-- hybrid_seed_sql.sql")
    lines.append("-- Generated by scripts/hybrid_seed.py from the SYNTHETIC finance")
    lines.append("-- extract only (data/raw/finance/finance_postings.csv). No HR data,")
    lines.append("-- no real data. Paste into the Azure portal Query editor during a")
    lines.append("-- create-test-delete session (see docs/HYBRID.md). Delete the table")
    lines.append("-- and the resource afterwards.")
    lines.append("")
    col_defs = ",\n    ".join(f"[{name}] {sqltype}" for name, sqltype in COLUMNS)
    lines.append(f"IF OBJECT_ID(N'dbo.{TABLE}', N'U') IS NOT NULL DROP TABLE dbo.{TABLE};")
    lines.append(f"CREATE TABLE dbo.{TABLE} (\n    {col_defs}\n);")
    lines.append("")
    col_names = ", ".join(f"[{name}]" for name, _ in COLUMNS)
    for row in rows:
        values = ", ".join(_sql_literal(name, row[name]) for name, _ in COLUMNS)
        lines.append(f"INSERT INTO dbo.{TABLE} ({col_names}) VALUES ({values});")
    lines.append("")
    return "\n".join(lines)


def write() -> str:
    sql = build_sql()
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(sql)
    return OUT


if __name__ == "__main__":
    path = write()
    print(f"wrote {os.path.relpath(path, REPO_ROOT)}")
